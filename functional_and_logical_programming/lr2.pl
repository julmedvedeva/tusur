% Задача 1 — подпоследовательность (вычёркивание)
% p(+A, +B): A получается из B вычёркиванием
  p([], _).                          % A пуст → да
  p([H|TA], [H|TB]) :-               % головы совпали
      p(TA, TB).
  p([HA|TA], [HB|TB]) :-             % головы разные
      HA \== HB,
      p([HA|TA], TB).                % A целиком, хвост B
% Задача 2 — соседние элементы
  % p(+X, +Y, +L): X и Y — соседние элементы L
  p(X, Y, [X, Y | _]).          % X, Y в начале
  p(X, Y, [_ | T]) :-           % иначе ищем в хвосте
      p(X, Y, T).
