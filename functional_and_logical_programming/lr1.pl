% Задача 1 — элементы, встречающиеся более одного раза

% p(+V, -L): L — элементы V, встречающиеся более одного раза
p(V, L) :- dups(V, L).

% dups: собрать дубликаты
dups([], []).
dups([H|T], [H|R]) :-       % H — дубликат
    member(H, T),
    delete(T, H, T1),       % убрать все H из хвоста
    dups(T1, R).
dups([H|T], R) :-           % H — одиночка
    \+ member(H, T),
    dups(T, R).
% Задача 2 — замена всех вхождений
% subst(+V, +X, +Y, -L): заменить все X на Y в списке V
subst([], _, _, []).
subst([X|T], X, Y, [Y|R]) :-      % голова = X → ставим Y
    subst(T, X, Y, R).
subst([H|T], X, Y, [H|R]) :-      % голова ≠ X → оставляем H
    H \== X,
    subst(T, X, Y, R).
